#!/usr/bin/env python3
"""Границы данных в журнале: читаются из разметки самого файла, а не задаются числом.

Класс растёт посреди года. Под каждый список в журнале отведён запас строк, запас
кончается, его расширяют - и любая граница, записанная в коде числом, в этот день
начинает молча терять данные: цикл `range(6, 28)` не падает на 25 детях, он просто
не доходит до последних трёх. Так уже было дважды: сначала в самом журнале, потом
в отчёте.

Поэтому границы берутся оттуда же, откуда их читает человек:

- сверху - строка шапки, опознаётся по подписи в колонке B («№», «Код», «Дата»);
- снизу - строка «ИТОГО…», которой кончается каждый лист журнала.

Пустые строки запаса между последней записью и «ИТОГО» безвредны: и генератор,
и проверка пропускают строку без ключевого поля. А вот заметки под «ИТОГО»
(на листе «Ученики» их две) как раз показывают, почему нижнюю границу нельзя
искать «последней непустой строкой»: непустые строки на листе есть и ниже итога.

Отдельная забота - соответствие «строка ученика -> колонка матрицы» на листах
«Участие», «Долги_год», «Долги_срок». Оно нигде не записано, а вычисляется как
`MC + (r - S_FIRST)`, и разъезжается молча: ребёнок получает чужие долги. Здесь
это соответствие проверяется по именам в шапке - см. matrix_col().
"""

TOTAL = "итого"          # строка «ИТОГО…» - нижняя граница данных на каждом листе
TOTAL_COLS = range(2, 7)  # в каких колонках она бывает: C у одних листов, D-E у других


def _fail(sheet, what, how):
    raise SystemExit(
        f"СБОРКА ОСТАНОВЛЕНА: на листе «{sheet.title}» {what}.\n"
        f"Границы данных читаются из журнала, а не заданы в коде: {how}")


def bounds(sheet, header):
    """(первая, последняя) строки данных листа.

    `header` - подпись первой колонки шапки (колонка B). Данные идут со следующей
    строки и до строки «ИТОГО…» не включительно. Нет шапки или нет итога - сборка
    останавливается: подставленный наугад диапазон потерял бы часть журнала молча.
    """
    top = next((r + 1 for r in range(1, sheet.max_row + 1)
                if str(sheet.cell(row=r, column=2).value or "").strip() == header), None)
    if top is None:
        _fail(sheet, f"не нашлась шапка «{header}» в колонке B",
              "проверьте, не переименована ли подпись колонки")
    for r in range(top, sheet.max_row + 1):
        for c in TOTAL_COLS:
            if str(sheet.cell(row=r, column=c).value or "").strip().lower().startswith(TOTAL):
                return top, r - 1
    _fail(sheet, "не нашлась строка «ИТОГО…»",
          "она отмечает конец данных - её нельзя удалять или переименовывать")


def matrix_col(uch, first, last, sheets):
    """Первая колонка участника в матрицах - и сверка, что колонки не разъехались.

    Колонка ребёнка на листах «Участие», «Долги_год», «Долги_срок» вычисляется из
    номера его строки на «Учениках». Связь эта нигде не записана, поэтому вставка
    строки в середину списка или лишняя колонка в матрице сдвигают её беззвучно:
    отчёт соберётся, просто у половины детей будут чужие долги.

    Сверять есть с чем: в шапке матрицы стоят те же имена, что в колонке C списка.
    Здесь они и сравниваются - строка за строкой, включая пустые строки запаса
    (пустой строке обязана отвечать пустая колонка). Расхождение останавливает
    сборку с указанием строки, колонки и обоих имён.
    """
    want = [str(uch.cell(row=r, column=3).value or "").strip() for r in range(first, last + 1)]
    mc = None
    for sh in sheets:
        head = next((r for r in range(1, sh.max_row + 1)
                     if str(sh.cell(row=r, column=2).value or "").strip() == "Код"), None)
        if head is None:
            _fail(sh, "не нашлась шапка «Код» в колонке B",
                  "по ней ищется строка с именами участников")
        col = next((c for c in range(2, sh.max_column + 1)
                    if str(sh.cell(row=head, column=c).value or "").strip() == "Сбор"), None)
        if col is None:
            _fail(sh, f"в шапке (строка {head}) нет колонки «Сбор»",
                  "имена участников идут сразу за ней")
        col += 1
        if mc is None:
            mc = col
        elif col != mc:
            _fail(sh, f"имена участников начинаются с другой колонки ({col}, а не {mc})",
                  "у всех трёх матриц колонки обязаны совпадать со списком учеников")

        bad = [(r, i) for i, r in enumerate(range(first, last + 1))
               if str(sh.cell(row=head, column=mc + i).value or "").strip() != want[i]]
        if bad:
            r, i = bad[0]
            got = str(sh.cell(row=head, column=mc + i).value or "").strip() or "пусто"
            _fail(sh, f"шапка разъехалась со списком учеников ({len(bad)} шт., первое - "
                      f"колонка {mc + i}: «{got}», а в строке {r} списка «{want[i] or 'пусто'}»)",
                  "порядок имён в матрицах обязан повторять порядок строк на «Учениках»")

        extra = [c for c in range(mc + len(want), sh.max_column + 1)
                 if str(sh.cell(row=head, column=c).value or "").strip()]
        if extra:
            name = str(sh.cell(row=head, column=extra[0]).value).strip()
            _fail(sh, f"в шапке есть имена за пределами списка (колонка {extra[0]}: «{name}»)",
                  "такой участник не попал бы в отчёт - добавьте его строкой на «Учениках»")
    return mc
